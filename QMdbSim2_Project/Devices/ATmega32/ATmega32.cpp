    inst->mdb.addPinPortMap("PB6", &PB6_I, &PB6_O, &PB6_C);
    inst->mdb.addPinPortMap("PB7", &PB7_I, &PB7_O, &PB7_C);
    inst->mdb.addPinPortMap("PC0", &PC0_I, &PC0_O, &PC0_C);
    inst->mdb.addPinPortMap("PC1", &PC1_I, &PC1_O, &PC1_C);
    inst->mdb.addPinPortMap("PC2", &PC2_I, &PC2_O, &PC2_C);
    inst->mdb.addPinPortMap("PC3", &PC3_I, &PC3_O, &PC3_C);
    inst->mdb.addPinPortMap("PC4", &PC4_I, &PC4_O, &PC4_C);
