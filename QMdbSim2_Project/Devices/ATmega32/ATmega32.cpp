    inst->mdb.addPinPortMap("PA4", &PA4_I, &PA4_O, &PA4_C);
    inst->mdb.addPinPortMap("PA5", &PA5_I, &PA5_O, &PA5_C);
    inst->mdb.addPinPortMap("PA6", &PA6_I, &PA6_O, &PA6_C);
    inst->mdb.addPinPortMap("PA7", &PA7_I, &PA7_O, &PA7_C);
    inst->mdb.addPinPortMap("PB0", &PB0_I, &PB0_O, &PB0_C);
    inst->mdb.addPinPortMap("PB1", &PB1_I, &PB1_O, &PB1_C);
